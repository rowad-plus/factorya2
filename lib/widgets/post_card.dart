  static final _teamKey = RegExp(r'^(name|role|image|image_path)(_(ar|en|tr))?$');

  /// Team-member posts: one entry per "[n]" member, shown as "<role> <name>"
  /// (e.g. "مدير محمد الالفي") instead of separate name / job-title rows — same as the site.
  List<({String name, String role, String image})> _teamMembers(PostModel p) {
    if (p.sourceEntity != 'factory_team') return const [];
    final raw = p.metadata?['change_rows'];
    if (raw is! List) return const [];
    final groups = <String, Map<String, String>>{};
    for (final r in raw) {
      if (r is! Map) continue;
      final key = '${r['key'] ?? ''}';
      final value = r['new'];
      if (!_teamKey.hasMatch(key) || value == null || '$value'.trim().isEmpty || '$value' == 'null') continue;
      final label = '${r['label_en'] ?? r['label_ar'] ?? ''}';
      final idx = RegExp(r'\[#?(\d+)\]').firstMatch(label)?.group(1) ?? '1';
      (groups[idx] ??= {})[key] = '$value';
    }
    final lang = L10n.i.lang;
    String pick(Map<String, String> g, String base) =>
        g['${base}_$lang'] ?? g['${base}_ar'] ?? g['${base}_en'] ?? g['${base}_tr'] ?? g[base] ?? '';
    return groups.values
        .map((g) => (name: pick(g, 'name'), role: pick(g, 'role'), image: g['image_path'] ?? g['image'] ?? ''))
        .where((m) => m.name.isNotEmpty || m.role.isNotEmpty)
        .toList();
  }

  Widget _memberRow(({String name, String role, String image}) m) {
    final img = m.image.startsWith('http') ? m.image : (m.image.isEmpty ? '' : 'https://factorya.net/storage/${m.image}');
    return Padding(
      padding: const EdgeInsets.only(bottom: 12),
      child: Row(children: [
        Container(
          width: 48, height: 48,
          clipBehavior: Clip.antiAlias,
          decoration: const BoxDecoration(shape: BoxShape.circle, color: Color(0xFFE4E4E7)),
          alignment: Alignment.center,
          child: img.isNotEmpty
              ? NetImage(url: img, width: 48, height: 48, fallback: '👤', fallbackSize: 20)
              : Text(m.name.isEmpty ? '؟' : String.fromCharCode(m.name.runes.first),
                  style: GoogleFonts.tajawal(fontSize: 18, fontWeight: FontWeight.w700, color: const Color(0xFF3F3F46))),
        ),
        const SizedBox(width: 12),
        Expanded(
          child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
            Text.rich(
              TextSpan(children: [
                if (m.role.isNotEmpty) TextSpan(text: '${m.role} ', style: const TextStyle(color: Color(0xFF7A5600))),
                TextSpan(text: m.name),
              ]),
              style: GoogleFonts.tajawal(fontSize: 15, fontWeight: FontWeight.w700, color: const Color(0xFF1A1A1A), height: 1.4),
            ),
            const SizedBox(height: 2),
            Text(tri('عضو فريق المصنع', 'Fabrika Ekip Üyesi', 'Factory Team Member'),
                style: GoogleFonts.tajawal(fontSize: 12, color: AppColors.muted)),
          ]),
        ),
      ]),
    );
  }

  Widget _autoBody(PostModel p) {
    final content = p.text;
    final members = _teamMembers(p);
    final allRows = visibleRows(p.metadata, content)
        .where((r) => members.isEmpty || !_teamKey.hasMatch(r.key))
        .toList();
    final hasLogo = allRows.any(_isLogoRow);
    final rows = allRows.where((r) => !_isLogoRow(r)).toList();
    final itemId = '${p.metadata?['item_id'] ?? ''}';
    final factoryId = p.authorFactoryId.isNotEmpty ? p.authorFactoryId : (itemId == 'null' ? '' : itemId);
    final factoryName = cleanName(p.authorName).isNotEmpty ? cleanName(p.authorName) : extractName(contentLead(content));
    final fallback = rows.isEmpty && members.isEmpty ? contentDetailBody(content) : '';
    final title = activityHeader(contentLead(content));
    final metaImage = [p.metadata?['image_url'], p.metadata?['image_path'], p.metadata?['image']]
        .whereType<String>()
        .firstWhere((u) => u.startsWith('http'), orElse: () => '');
    final images = [...p.imageUrls, if (metaImage.isNotEmpty && !p.imageUrls.contains(metaImage)) metaImage];
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: 12),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          _titleBar(title.isNotEmpty ? title : t('post.contact_updated', 'تحديث بيانات الاتصال'), onTap: _openFactory),
          for (final m in members) _memberRow(m),
          for (final r in rows) _row(r),
          if (hasLogo && factoryName.isNotEmpty) _logoCaption(factoryName, factoryId),
          if (fallback.isNotEmpty)
            Container(
              padding: const EdgeInsets.all(12),
              decoration: BoxDecoration(color: Colors.white, borderRadius: BorderRadius.circular(6), border: Border.all(color: const Color(0xFFE2E8F0))),
              child: Text(fallback, style: GoogleFonts.tajawal(fontSize: 13, color: const Color(0xFF333333), height: 1.7)),
            ),
          _images(images),
        ],
      ),
    );
  }

