                                decoration: BoxDecoration(color: AppColors.bg, borderRadius: BorderRadius.circular(10)),
                                child: Column(
                                  crossAxisAlignment: CrossAxisAlignment.start,
                                  children: [
                                    Row(children: [
                                      Expanded(child: Text(c['name']!, style: GoogleFonts.tajawal(fontSize: 11.5, fontWeight: FontWeight.w700))),
                                      if ((c['id'] ?? '').isNotEmpty && c['user_id'] != '${AuthService.i.userId ?? ''}')
                                        GestureDetector(onTap: () => _commentMenu(c), child: const Icon(Icons.more_horiz, size: 18, color: gray)),
                                    ]),
                                    Text(c['text']!, style: GoogleFonts.tajawal(fontSize: 12, color: const Color(0xFF444444))),
                                  ],
                                ),
                              ),
                            ),
                          ],
                        ),
                      )),
                  Row(
                    children: [
                      Expanded(
                        child: TextField(
                          controller: _commentCtrl,
                          onSubmitted: (_) => _addComment(),
                          style: GoogleFonts.tajawal(fontSize: 13),
                          decoration: InputDecoration(
                            hintText: t('post.comment_placeholder', 'اكتب تعليقك هنا...'),
                            hintStyle: GoogleFonts.tajawal(fontSize: 12),
                            contentPadding: const EdgeInsets.symmetric(horizontal: 12, vertical: 8),
                            border: OutlineInputBorder(borderRadius: BorderRadius.circular(20), borderSide: const BorderSide(color: AppColors.border)),
                            enabledBorder: OutlineInputBorder(borderRadius: BorderRadius.circular(20), borderSide: const BorderSide(color: AppColors.border)),
                            focusedBorder: OutlineInputBorder(borderRadius: BorderRadius.circular(20), borderSide: const BorderSide(color: AppColors.gold)),
                          ),
                        ),
                      ),
                      const SizedBox(width: 6),
                      GestureDetector(
                        onTap: _addComment,
                        child: Container(width: 34, height: 34, decoration: const BoxDecoration(color: AppColors.gold, shape: BoxShape.circle), child: const Icon(Icons.send_rounded, color: AppColors.dark, size: 15)),
                      ),
                    ],
                  ),
                ],
              ),
            ),
        ],
      ),
    );
