  Widget _row(MetaRow r) {
    final long = r.value.length > 15 || r.key.contains('address') || RegExp('activit', caseSensitive: false).hasMatch('${r.key} ${r.label}');
    final values = formatValue(r.value, r.key, r.label);
    final ltr = isLtrValue(r.value, r.key, r.label);
    final pill = Container(
      padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 4),
      decoration: BoxDecoration(color: const Color(0xFFE6F4EA), borderRadius: BorderRadius.circular(6)),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        mainAxisSize: MainAxisSize.min,
        children: [
          for (final v in values)
            Directionality(
              textDirection: (L10n.i.isRtl && !ltr) ? TextDirection.rtl : TextDirection.ltr,
              child: Text(v, style: GoogleFonts.tajawal(fontSize: 13, fontWeight: FontWeight.w700, color: const Color(0xFF1B5E20), height: 1.5)),
            ),
        ],
      ),
    );
    final label = Text(r.label, style: GoogleFonts.tajawal(fontSize: 13, fontWeight: FontWeight.w500, color: const Color(0xFF333333)));
    // No border / padding around the row (same as the site's .css-195p2vq override).
    return Container(
      width: double.infinity,
      margin: const EdgeInsets.only(bottom: 10),
      child: long
          ? Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [label, const SizedBox(height: 8), pill])
          : Row(mainAxisAlignment: MainAxisAlignment.spaceBetween, crossAxisAlignment: CrossAxisAlignment.center, children: [label, Flexible(child: pill)]),
    );
  }

  bool _isLogoRow(MetaRow r) => RegExp(r'logo|الشعار|شعار|logosu', caseSensitive: false).hasMatch('${r.key} ${r.label}');

