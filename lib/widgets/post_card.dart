            decoration: const BoxDecoration(border: Border(top: BorderSide(color: Color(0xFFF2F4F7)))),
            child: Row(
              children: [
                _action(_liked ? Icons.favorite : Icons.favorite_border, '${t('post.like', 'إعجاب')}${_likes > 0 ? ' ($_likes)' : ''}', _liked ? AppColors.red : const Color(0xFF6B6B6B), _toggleLike),
